// QuarterDateBounds 해당 연·분기의 첫째 날과 마지막 날(YYYY-MM-DD).
func QuarterDateBounds(year, quarter int) (from, to string) {
	start, end := QuarterMonthRange(quarter)
	if start == 0 || year < 1 {
		return "", ""
	}
	from = fmt.Sprintf("%04d-%02d-01", year, start)
	last := time.Date(year, time.Month(end)+1, 0, 0, 0, 0, 0, time.UTC)
	to = last.Format("2006-01-02")
	return
}

// VisitInCalendarQuarter 방문일(일정 확정)이 그 달력 분기에 속하는지.
// 날짜가 비어 있거나 형식이 짧으면 미확정으로 본다.
func VisitInCalendarQuarter(visitDate string, year, quarter int) bool {
	d := strings.TrimSpace(visitDate)
	if len(d) < 10 {
		return false
	}
	d = d[:10]
	from, to := QuarterDateBounds(year, quarter)
	if from == "" {
		return false
	}
	return d >= from && d <= to
}

// InspectionCycleDue 점검주기가 해당 월에 도래하는지 (기획서 §17.2).
// 월=매월, 홀수격월=1·3·5·7·9·11, 짝수격월=2·4·6·8·10·12, 분기=1·4·7·10, 반기=1·7, 년1회=1월.
// 분기 자동 초안은 이 첫 달에 1건만 만든다. 확인에서 고른 날이 있으면 초안을 만들지 않는다(D-74).
// 분기 의무 충족은 InspectionCycleDue가 아니라 QuarterObligations(달력 분기 안 1회)로 판정한다(D-70).
func InspectionCycleDue(cycle string, month int) bool {
	if month < 1 || month > 12 {
		return false
	}
	switch strings.TrimSpace(cycle) {
	case "", "monthly":
		return true
	case "odd_bimonthly":
		return month%2 == 1
	case "even_bimonthly":
		return month%2 == 0
	case "quarterly":
		return month == 1 || month == 4 || month == 7 || month == 10
	case "semi":
		return month == 1 || month == 7
	case "yearly":
		return month == 1
	default:
		return true
	}
}

// NextMonthStart 서버 시각 기준 다음 달 1일 0시.
func NextMonthStart(now time.Time) time.Time {
	loc := now.Location()
	if loc == nil {
		loc = time.Local
	}
	first := time.Date(now.Year(), now.Month(), 1, 0, 0, 0, 0, loc)
	return first.AddDate(0, 1, 0)
}

// VisitDeleteProtected 당월·이전 달 방문은 삭제 불가 (§23.11). 기준은 다음 달 1일.
// 방문일이 비어 있으면 아직 실적이 아니므로 보호하지 않는다(계획 복사 초안).
func VisitDeleteProtected(visitDate string, now time.Time) bool {
	d := strings.TrimSpace(visitDate)
	if d == "" {
		return false
	}
	if len(d) < 10 {
		return true
	}
	return d[:10] < NextMonthStart(now).Format("2006-01-02")
}

// VisitAutoReassignProtected 자동 배정 재생성 보호. 기준은 오늘(당일 포함). §34.4.5
func VisitAutoReassignProtected(visitDate string, now time.Time) bool {
	d := strings.TrimSpace(visitDate)
	if d == "" {
		return false
	}
	if len(d) < 10 {
		return true
	}
	today := now.Format("2006-01-02")
	return d[:10] <= today
}

// ErrGeneratePastMonth 지난 달 자동 배정 거부. §34.4.5
