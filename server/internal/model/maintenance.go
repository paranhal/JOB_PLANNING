// VisitProductSlotKey 방문의 점검대상을 슬롯 키로 정규화한다(klas/rfid/generic).
func VisitProductSlotKey(product string) string {
	raw := strings.TrimSpace(product)
	if raw == "" {
		return "generic"
	}
	compact := strings.ToUpper(raw)
	compact = strings.ReplaceAll(compact, " ", "")
	compact = strings.ReplaceAll(compact, "-", "")
	compact = strings.ReplaceAll(compact, "_", "")
	if strings.Contains(raw, "앤로보") || strings.Contains(compact, "ANROBO") || strings.Contains(compact, "RFID") {
		return "rfid"
	}
	if strings.Contains(compact, "KLAS") {
		return "klas"
	}
	return "generic"
}

// SiteDueProductSlots 그 달 주기가 도래한 사이트의 점검대상 슬롯(표시명 포함).
func SiteDueProductSlots(cfg MaintenanceSiteConfig, month int) []UnassignedMonthSlot {
	if !InspectionCycleDue(cfg.InspectionCycle, month) {
		return nil
	}
	name := cfg.ShortName
	if name == "" {
		name = cfg.OrgName
	}
	base := UnassignedMonthSlot{
		CustomerID: cfg.CustomerID, OrgName: cfg.OrgName, ShortName: name, Cycle: cfg.InspectionCycle, OrgID: cfg.OrgID,
	}
	var out []UnassignedMonthSlot
	if cfg.Products != nil {
		for _, p := range cfg.Products {
			if !p.IsActive {
				continue
			}
			s := base
			s.ProductType = p.Name
			s.SlotKey = p.Code
			out = append(out, s)
		}
		if len(out) == 0 {
			s := base
			s.ProductType = ""
			s.SlotKey = "generic"
			out = append(out, s)
		}
		return out
	}
	if cfg.HasKlas {
		s := base
		s.ProductType = "KLAS"
		s.SlotKey = "klas"
		out = append(out, s)
	}
	if cfg.HasRfid {
		s := base
		s.ProductType = "앤로보틱스"
		s.SlotKey = "rfid"
		out = append(out, s)
	}
	if len(out) == 0 {
		s := base
		s.ProductType = ""
		s.SlotKey = "generic"
		out = append(out, s)
	}
	return out
}

// MonthPrefix YYYY-MM-
func MonthPrefix(year, month int) string {
	return fmt.Sprintf("%04d-%02d-", year, month)
}

// CalendarQuarter 달력 분기(1~4). month 가 1~12가 아니면 0.
func CalendarQuarter(month int) int {
	if month < 1 || month > 12 {
		return 0
	}
	return (month-1)/3 + 1
}

// QuarterMonthRange 분기의 시작·끝 월. quarter 가 1~4가 아니면 0,0.
func QuarterMonthRange(quarter int) (start, end int) {
	if quarter < 1 || quarter > 4 {
		return 0, 0
	}
	start = (quarter-1)*3 + 1
	end = start + 2
	return
}

// IsLastMonthOfQuarter 분기 마지막 달(3·6·9·12).
func IsLastMonthOfQuarter(month int) bool {
	return month == 3 || month == 6 || month == 9 || month == 12
}

// IsQuarterlyCycle 점검주기가 분기인지.
func IsQuarterlyCycle(cycle string) bool {
	return strings.TrimSpace(cycle) == "quarterly"
}

// IsPeriodCycle 기간 안 1회 주기(분기·반기·년1회).
func IsPeriodCycle(cycle string) bool {
	switch strings.TrimSpace(cycle) {
	case "quarterly", "semi", "yearly":
		return true
	default:
		return false
	}
}

// CyclePeriod 주기 한 구간(분기·반기·연).
type CyclePeriod struct {
	Cycle      string
	Index      int
	StartMonth int
	EndMonth   int
}

// CyclePeriodOf 그 달이 속한 기간. 기간 주기가 아니면 ok=false.
func CyclePeriodOf(cycle string, month int) (CyclePeriod, bool) {
	if month < 1 || month > 12 {
		return CyclePeriod{}, false
	}
	switch strings.TrimSpace(cycle) {
	case "quarterly":
		q := CalendarQuarter(month)
		s, e := QuarterMonthRange(q)
		return CyclePeriod{Cycle: "quarterly", Index: q, StartMonth: s, EndMonth: e}, true
	case "semi":
		if month <= 6 {
			return CyclePeriod{Cycle: "semi", Index: 1, StartMonth: 1, EndMonth: 6}, true
		}
		return CyclePeriod{Cycle: "semi", Index: 2, StartMonth: 7, EndMonth: 12}, true
	case "yearly":
		return CyclePeriod{Cycle: "yearly", Index: 1, StartMonth: 1, EndMonth: 12}, true
	default:
		return CyclePeriod{}, false
	}
}

// PeriodDateBounds 기간의 첫째 날과 마지막 날.
func PeriodDateBounds(year int, p CyclePeriod) (from, to string) {
	if year < 1 || p.StartMonth < 1 || p.EndMonth < 1 {
		return "", ""
	}
	from = fmt.Sprintf("%04d-%02d-01", year, p.StartMonth)
	last := time.Date(year, time.Month(p.EndMonth)+1, 0, 0, 0, 0, 0, time.UTC)
	to = last.Format("2006-01-02")
	return
}

// VisitInCyclePeriod 방문일이 그 기간 안인지.
func VisitInCyclePeriod(visitDate string, year int, p CyclePeriod) bool {
	d := strings.TrimSpace(visitDate)
	if len(d) < 10 {
		return false
	}
	d = d[:10]
	from, to := PeriodDateBounds(year, p)
	if from == "" {
		return false
	}
	return d >= from && d <= to
}

func (p CyclePeriod) LabelShort() string {
	switch p.Cycle {
	case "semi":
		if p.Index == 1 {
			return "상반기"
		}
		return "하반기"
	case "yearly":
		return "연간"
	default:
		return fmt.Sprintf("%d분기", p.Index)
	}
}

