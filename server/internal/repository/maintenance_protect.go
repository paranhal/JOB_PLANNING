// ErrVisitDeleteProtected 당월·이전 달 방문 삭제 거부 (§23.11).
var ErrVisitDeleteProtected = fmt.Errorf("당월·이전 달 방문은 삭제할 수 없습니다")

const (
	// DupSkipCompleted Drop 만 완료된 경우(선정 오류 방어).
	DupSkipCompleted = "완료된 방문"
	// DupSkipBothDone 같은 슬롯의 방문이 둘 다 완료.
	DupSkipBothDone = "둘 다 완료됨"
	// DupSkipRecord 비고·시간·장비·사인·결과서가 있어 자동 삭제 불가.
	DupSkipRecord = "조치 기록이 있어 직접 확인이 필요합니다"
)

// DuplicateDrop 중복 정리 시 지워질 방문과 남을 방문.
type DuplicateDrop struct {
	Drop       model.MaintenanceVisit
	Keep       model.MaintenanceVisit
	SkipReason string
}

func (d DuplicateDrop) Deletable() bool {
	return strings.TrimSpace(d.SkipReason) == ""
}

func (d DuplicateDrop) StatusLabel() string {
	switch strings.TrimSpace(d.SkipReason) {
	case "":
		return "삭제 예정"
	case DupSkipCompleted:
		return "제외 — 완료된 방문"
	case DupSkipRecord:
		return "제외 — 조치 기록 있음"
	case DupSkipBothDone:
		return "제외 — 둘 다 완료"
	default:
		return "제외 — " + d.SkipReason
	}
}

func (d DuplicateDrop) SiteName() string {
	if s := strings.TrimSpace(d.Drop.ShortName); s != "" {
		return s
	}
	return strings.TrimSpace(d.Drop.OrgName)
}

// GuardPlanDelete 계획 삭제 가능 여부를 검사한다. 핸들러가 백업 전에 호출한다.
func (r *MaintenanceRepo) GuardPlanDelete(planID string) error {
	return r.guardPlanDelete(planID)
}

func (r *MaintenanceRepo) guardPlanDelete(planID string) error {
	plan, err := r.GetPlan(planID)
	if err != nil || plan == nil {
		return fmt.Errorf("계획을 찾을 수 없습니다")
	}
	now := r.nowTime()
	if plan.PlanYear < now.Year() {
		return fmt.Errorf("%d년 계획은 삭제할 수 없습니다. 보관으로만 내릴 수 있습니다", plan.PlanYear)
	}
	st, err := r.PlanDeleteStats(planID)
	if err != nil {
		return err
	}
	if st.Completed > 0 {
		return fmt.Errorf("완료된 방문 %d건이 있어 계획을 삭제할 수 없습니다. 먼저 보관 상태로 바꾸세요", st.Completed)
	}
	if st.Protected > 0 {
		return fmt.Errorf("%s", model.ProtectedVisitRangeMessage(now, st.Protected))
	}
	return nil
}

// PlanDeleteStats 계획 삭제 영향 범위.
type PlanDeleteStats struct {
	Total     int
	Completed int
	Protected int
}

func (r *MaintenanceRepo) PlanDeleteStats(planID string) (PlanDeleteStats, error) {
	visits, err := r.ListVisits(planID)
	if err != nil {
		return PlanDeleteStats{}, err
	}
	now := r.nowTime()
	var st PlanDeleteStats
	st.Total = len(visits)
	for _, v := range visits {
		if v.Completed {
			st.Completed++
		}
		if model.VisitDeleteProtected(v.VisitDate, now) {
			st.Protected++
		}
	}
	return st, nil
}

// AutoAssignMonthStats 확인 화면용 월별 자동 배정 영향. §34.4.5
type AutoAssignMonthStats struct {
	Year          int
	Month         int
	Today         string
	PastMonth     bool
	DeleteCount   int
	CompletedKeep int
	PastKeep      int
	ManualKeep    int
	Visits        []model.MaintenanceVisit
}

func (r *MaintenanceRepo) AutoAssignMonthStats(planID string, year, month int) (AutoAssignMonthStats, error) {
	st := AutoAssignMonthStats{Year: year, Month: month}
	now := r.nowTime()
	st.Today = now.Format("2006-01-02")
	st.PastMonth = model.IsPastGenerateMonth(year, month, now)
	visits, err := r.ListVisitsByMonth(planID, year, month)
	if err != nil {
		return st, err
	}
	st.Visits = visits
	for _, v := range visits {
		if v.Completed {
			st.CompletedKeep++
			continue
		}
		if !v.AutoGenerated {
			st.ManualKeep++
			continue
		}
		if model.VisitAutoReassignProtected(v.VisitDate, now) {
			st.PastKeep++
			continue
		}
		if !st.PastMonth {
			st.DeleteCount++
		} else {
			st.PastKeep++
		}
	}
	return st, nil
}

func (r *MaintenanceRepo) AutoVisitDeleteStats(planID string) (deletable, protected int, err error) {
	visits, err := r.ListVisits(planID)
	if err != nil {
		return 0, 0, err
	}
	now := r.nowTime()
	for _, v := range visits {
		if !v.AutoGenerated {
			continue
		}
		if v.Completed || model.VisitDeleteProtected(v.VisitDate, now) {
			protected++
			continue
		}
		deletable++
	}
	return deletable, protected, nil
}

func (r *MaintenanceRepo) ListDuplicateDrops(planID string, year, month int) ([]DuplicateDrop, error) {
	visits, err := r.ListVisitsByMonth(planID, year, month)
	if err != nil {
		return nil, err
	}
	return r.duplicateDropsFromVisits(visits)
}

func (r *MaintenanceRepo) duplicateDropsFromVisits(visits []model.MaintenanceVisit) ([]DuplicateDrop, error) {
	return r.classifyCollectedDrops(r.collectDuplicateDrops(visits))
}

func (r *MaintenanceRepo) duplicateDropsFromVisitsRange(visits []model.MaintenanceVisit, year, month int) ([]DuplicateDrop, error) {
	if month >= 1 && month <= 12 {
		return r.duplicateDropsFromVisits(filterVisitsInMonth(visits, year, month))
	}
	var collected []DuplicateDrop
	for m := 1; m <= 12; m++ {
		collected = append(collected, r.collectDuplicateDrops(filterVisitsInMonth(visits, year, m))...)
	}
	return r.classifyCollectedDrops(collected)
}

func (r *MaintenanceRepo) collectDuplicateDrops(visits []model.MaintenanceVisit) []DuplicateDrop {
	type key struct {
		cust  string
		slot  string
		round int
	}
	best := map[key]model.MaintenanceVisit{}
	var drops []DuplicateDrop
	for _, v := range visits {
		k := key{v.CustomerID, model.VisitProductSlotKey(v.ProductType), v.VisitRound()}
		cur, ok := best[k]
		if !ok {
			best[k] = v
			continue
		}
		keep, lose := pickBetterMonthVisit(cur, v)
		best[k] = keep
		drops = append(drops, DuplicateDrop{Drop: lose, Keep: keep})
	}
	for _, v := range visits {
		if model.VisitProductSlotKey(v.ProductType) != "generic" {
			continue
		}
		var prod model.MaintenanceVisit
		for _, slot := range []string{"klas", "rfid"} {
			if p, ok := best[key{v.CustomerID, slot, v.VisitRound()}]; ok {
				prod = p
				break
			}
		}
		if prod.VisitID == "" {
			continue
		}
		keep, lose := pickBetterMonthVisit(v, prod)
		drops = append(drops, DuplicateDrop{Drop: lose, Keep: keep})
		if keep.VisitID == v.VisitID {
			delete(best, key{prod.CustomerID, model.VisitProductSlotKey(prod.ProductType), prod.VisitRound()})
			best[key{v.CustomerID, "generic", v.VisitRound()}] = v
		} else {
			delete(best, key{v.CustomerID, "generic", v.VisitRound()})
		}
	}
	seen := map[string]struct{}{}
	kept := map[string]struct{}{}
	for _, v := range best {
		kept[v.VisitID] = struct{}{}
	}
	var out []DuplicateDrop
	for _, d := range drops {
		if d.Drop.VisitID == "" {
			continue
		}
		if _, ok := seen[d.Drop.VisitID]; ok {
			continue
		}
		if _, ok := kept[d.Drop.VisitID]; ok {
			continue
		}
		seen[d.Drop.VisitID] = struct{}{}
		out = append(out, d)
	}
	return out
}

func (r *MaintenanceRepo) classifyCollectedDrops(out []DuplicateDrop) ([]DuplicateDrop, error) {
	checkIDs := make([]string, 0, len(out))
	for _, d := range out {
		checkIDs = append(checkIDs, d.Drop.VisitID)
	}
	linked := r.visitIDsWithLinkedAction(checkIDs)
	for i := range out {
		r.classifyDuplicateDrop(&out[i], linked[out[i].Drop.VisitID])
	}
	return out, nil
}

func (r *MaintenanceRepo) classifyDuplicateDrop(d *DuplicateDrop, linkedAction bool) {
	if d == nil {
		return
	}
	if d.Drop.Completed && d.Keep.Completed {
		d.SkipReason = DupSkipBothDone
		return
	}
	if d.Drop.Completed {
		d.SkipReason = DupSkipCompleted
		return
	}
	if d.Keep.VisitID == "" || d.Keep.PlanID != d.Drop.PlanID || d.Keep.CustomerID != d.Drop.CustomerID {
		d.SkipReason = "남을 방문이 같은 슬롯에 없습니다"
		return
	}
	if visitYearMonth(d.Drop.VisitDate) != visitYearMonth(d.Keep.VisitDate) {
		d.SkipReason = "남을 방문이 같은 슬롯에 없습니다"
		return
	}
	if visitHasLocalAction(d.Drop) || linkedAction {
		d.SkipReason = DupSkipRecord
	}
}

func visitHasLocalAction(v model.MaintenanceVisit) bool {
	return strings.TrimSpace(v.Notes) != "" || strings.TrimSpace(v.StartTime) != "" || strings.TrimSpace(v.EndTime) != ""
}

func (r *MaintenanceRepo) visitIDsWithLinkedAction(ids []string) map[string]bool {
	out := map[string]bool{}
	ids = uniqueNonEmpty(ids)
	if r == nil || r.db == nil || len(ids) == 0 {
		return out
	}
	tables := []string{
		"maintenance_visit_targets",
		"maintenance_visit_signatures",
		"maintenance_visit_reports",
		"maintenance_reports",
	}
	for i := 0; i < len(ids); i += inClauseChunk {
		end := i + inClauseChunk
		if end > len(ids) {
			end = len(ids)
		}
		part := ids[i:end]
		ph := placeholders(len(part))
		args := iface(part)
		for _, tbl := range tables {
			rows, err := r.db.Query(`SELECT DISTINCT visit_id FROM `+tbl+` WHERE visit_id IN (`+ph+`)`, args...)
			if err != nil {
				continue
			}
			for rows.Next() {
				var id string
				if rows.Scan(&id) == nil && strings.TrimSpace(id) != "" {
					out[id] = true
				}
			}
			rows.Close()
		}
	}
	return out
}

func visitYearMonth(date string) string {
	date = strings.TrimSpace(date)
	if len(date) >= 7 {
		return date[:7]
	}
	return date
}

func (r *MaintenanceRepo) visitHasActionRecord(v model.MaintenanceVisit) bool {
	if visitHasLocalAction(v) {
		return true
	}
	targets, err := r.ListVisitTargets(v.VisitID)
	if err == nil && len(targets) > 0 {
		return true
	}
	return r.visitHasSignatureOrReport(v.VisitID)
}

func (r *MaintenanceRepo) visitHasSignatureOrReport(visitID string) bool {
	visitID = strings.TrimSpace(visitID)
	if visitID == "" || r == nil || r.db == nil {
		return false
	}
	tables := []string{
		"maintenance_visit_signatures",
		"maintenance_visit_reports",
		"maintenance_reports",
	}
	for _, tbl := range tables {
		var n int
		q := fmt.Sprintf(`SELECT COUNT(*) FROM %s WHERE visit_id=?`, tbl)
		if err := r.db.QueryRow(q, visitID).Scan(&n); err != nil {
			continue
		}
		if n > 0 {
			return true
		}
	}
	return false
}

func (r *MaintenanceRepo) CountDuplicateDrops(planID string, year int, month int) (int, error) {
	visits, err := r.ListVisits(planID)
	if err != nil {
		return 0, err
	}
	return r.CountDuplicateDropsFromVisits(visits, year, month)
}

func (r *MaintenanceRepo) CountDuplicateDropsFromVisits(visits []model.MaintenanceVisit, year, month int) (int, error) {
	d, err := r.duplicateDropsFromVisitsRange(visits, year, month)
	return len(d), err
}

func filterVisitsInMonth(visits []model.MaintenanceVisit, year, month int) []model.MaintenanceVisit {
	from, to := monthDateBounds(year, month)
	var out []model.MaintenanceVisit
	for _, v := range visits {
		d := strings.TrimSpace(v.VisitDate)
		if d >= from && d < to {
			out = append(out, v)
		}
	}
	return out
}

// deleteVisitAllowProtectedDuplicate 중복 정리 전용. allowProtectedDuplicate=true 일 때만
// §23.11 당월 보호를 건너뛰고 removeVisitRow 한다. 일반 DeleteVisit 는 이 인자를 받지 않는다.
func (r *MaintenanceRepo) deleteVisitAllowProtectedDuplicate(visitID string, allowProtectedDuplicate bool) error {
	if !allowProtectedDuplicate {
		return r.DeleteVisit(visitID)
	}
	v, err := r.GetVisit(visitID)
	if err != nil {
		return err
	}
	if v == nil {
		return fmt.Errorf("방문을 찾을 수 없습니다")
	}
	if v.Completed {
		return fmt.Errorf("완료된 방문은 삭제할 수 없습니다")
	}
	if r.visitHasActionRecord(*v) {
		return fmt.Errorf("%s", DupSkipRecord)
	}
	return r.removeVisitRow(visitID)
}

// DeleteVisitIDs 기간 보호 대상은 건너뛰고 나머지만 지운다. skipped 는 제외 건수.
func (r *MaintenanceRepo) DeleteVisitIDs(ids []string) (deleted, skipped int, err error) {
	now := r.nowTime()
	for _, id := range ids {
		id = strings.TrimSpace(id)
		if id == "" {
			continue
		}
		v, getErr := r.GetVisit(id)
		if getErr != nil || v == nil {
			skipped++
			continue
		}
		if model.VisitDeleteProtected(v.VisitDate, now) {
			skipped++
			continue
		}
		if delErr := r.DeleteVisit(id); delErr != nil {
			if errors.Is(delErr, ErrVisitDeleteProtected) {
				skipped++
				continue
			}
			return deleted, skipped, delErr
		}
		deleted++
	}
	return deleted, skipped, nil
}
