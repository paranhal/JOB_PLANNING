// InsertVisitFull 담당자·점검대상·완료여부까지 지정해 방문을 넣는다.
func (r *MaintenanceRepo) InsertVisitFull(v model.MaintenanceVisit) error {
	id := v.VisitID
	if id == "" {
		id = randomID("mvs_")
	}
	auto := 0
	if v.AutoGenerated {
		auto = 1
	}
	completed := 0
	completedDate := ""
	if v.Completed {
		completed = 1
		completedDate = v.DoneOn()
	}
	if v.EntryCategory == "" {
		v.EntryCategory = "normal"
	}
	if strings.TrimSpace(v.ProjectID) == "" {
		v.ProjectID = resolveStoredProjectID(r.db, v.CustomerID, v.ProductType, model.ScopeWorkMaintenance)
	}
	_, err := r.db.Exec(`
		INSERT INTO maintenance_visits
		(visit_id, plan_id, visit_date, customer_id, sort_order, auto_generated, entry_category, notes,
		 assignee, product_type, completed, completed_date, project_id)
		VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)`,
		id, v.PlanID, v.VisitDate, v.CustomerID, v.SortOrder, auto, v.EntryCategory, nullIfEmpty(v.Notes),
		nullIfEmpty(v.Assignee), nullIfEmpty(v.ProductType), completed, nullIfEmpty(completedDate),
		nullIfEmpty(v.ProjectID))
	return err
}

// UpdateVisit 방문 일정·담당자·점검대상 등을 수정한다.
func (r *MaintenanceRepo) UpdateVisit(v model.MaintenanceVisit) error {
	if v.VisitID == "" {
		return fmt.Errorf("방문 ID가 없습니다")
	}
	if v.VisitDate == "" || v.CustomerID == "" {
		return fmt.Errorf("날짜와 고객을 선택하세요")
	}
	if v.EntryCategory == "" {
		v.EntryCategory = "normal"
	}
	completed := 0
	completedDate := ""
	if v.Completed {
		completed = 1
		completedDate = v.DoneOn()
	}
	if err := r.clearVisitSlotConflict(v.PlanID, v.VisitDate, v.CustomerID, v.ProductType, v.VisitID); err != nil {
		return err
	}
	if strings.TrimSpace(v.ProjectID) == "" {
		v.ProjectID = resolveStoredProjectID(r.db, v.CustomerID, v.ProductType, model.ScopeWorkMaintenance)
	}
	before := rowJSON(r.db, "maintenance_visits", "visit_id", v.VisitID)
	res, err := r.db.Exec(`
		UPDATE maintenance_visits SET
			visit_date=?, customer_id=?, entry_category=?, notes=?,
			assignee=?, product_type=?, completed=?, completed_date=?, project_id=?
		WHERE visit_id=?`,
		v.VisitDate, v.CustomerID, v.EntryCategory, nullIfEmpty(v.Notes),
		nullIfEmpty(v.Assignee), nullIfEmpty(v.ProductType),
		completed, nullIfEmpty(completedDate), nullIfEmpty(v.ProjectID), v.VisitID)
	if err != nil {
		return err
	}
	n, _ := res.RowsAffected()
	if n == 0 {
		return fmt.Errorf("방문을 찾을 수 없습니다")
	}
	logUpdate(r.db, "maintenance_visits", "visit_id", v.VisitID, v.VisitDate, before)
	return nil
}

// clearVisitSlotConflict 옮기려는 날짜에 같은 기관·점검대상이 있으면 그 건(다른 ID)을 지워 1건만 남긴다.
func (r *MaintenanceRepo) clearVisitSlotConflict(planID, visitDate, customerID, product, keepID string) error {
	planID = strings.TrimSpace(planID)
	visitDate = strings.TrimSpace(visitDate)
	customerID = strings.TrimSpace(customerID)
	keepID = strings.TrimSpace(keepID)
	if planID == "" || visitDate == "" || customerID == "" || keepID == "" {
		return nil
	}
	rows, err := r.db.Query(`
		SELECT visit_id FROM maintenance_visits
		WHERE plan_id=? AND visit_date=? AND customer_id=?
		  AND COALESCE(product_type,'') = COALESCE(?, '')
		  AND visit_id != ?`,
		planID, visitDate, customerID, strings.TrimSpace(product), keepID)
	if err != nil {
		return err
	}
	var ids []string
	for rows.Next() {
		var id string
		if err := rows.Scan(&id); err != nil {
			rows.Close()
			return err
		}
		ids = append(ids, id)
	}
	rows.Close()
	for _, id := range ids {
		if err := r.DeleteVisit(id); err != nil {
			if err == ErrVisitDeleteProtected {
				return fmt.Errorf("당월·이전 달 방문과 겹쳐 옮길 수 없습니다")
			}
			return err
		}
	}
	return nil
}

// CollapseDuplicateMonthVisits 같은 달·같은 기관·같은 점검대상은 1건만 남긴다.
// 완료 건·점검대상이 있는 건·늦은 방문일을 우선한다. 빈 점검대상은 제품 건이 있으면 제거한다.
func (r *MaintenanceRepo) CollapseDuplicateMonthVisits(planID string, year, month int) (deleted, skipped int, err error) {
	drops, err := r.ListDuplicateDrops(planID, year, month)
	if err != nil {
		return 0, 0, err
	}
	var ids []string
	for _, d := range drops {
		ids = append(ids, d.Drop.VisitID)
	}
	deleted, skipped, err = r.DeleteVisitIDs(ids)
	return deleted, skipped, err
}

func pickBetterMonthVisit(a, b model.MaintenanceVisit) (keep, lose model.MaintenanceVisit) {
	score := func(v model.MaintenanceVisit) int {
		s := 0
		if v.Completed {
			s += 100
		}
		if strings.TrimSpace(v.ProductType) != "" {
			s += 10
		}
		if !v.AutoGenerated {
			s += 5
		}
		s += len(v.VisitDate)
		return s
	}
	if score(b) > score(a) || (score(b) == score(a) && b.VisitDate > a.VisitDate) {
		return b, a
	}
	return a, b
}

// ListUnassignedMonthSlots 주기는 도래했는데 그 달에 방문 일정이 없는 사이트×점검대상.
func (r *MaintenanceRepo) ListUnassignedMonthSlots(planID string, year, month int) ([]model.UnassignedMonthSlot, error) {
	configs, err := r.ListSiteConfigs()
	if err != nil {
		return nil, err
	}
	visits, err := r.ListVisitsByMonth(planID, year, month)
	if err != nil {
		return nil, err
	}
	covered := map[string]map[string]bool{} // customer -> slotKey
	for _, v := range visits {
		if covered[v.CustomerID] == nil {
			covered[v.CustomerID] = map[string]bool{}
		}
		covered[v.CustomerID][model.VisitProductSlotKey(v.ProductType)] = true
	}
	var out []model.UnassignedMonthSlot
	for _, cfg := range configs {
		slots := model.SiteDueProductSlots(cfg, month)
		have := covered[cfg.CustomerID]
		genericUsed := have["generic"]
		for _, s := range slots {
			if have[s.SlotKey] {
				continue
			}
			if genericUsed && s.SlotKey != "generic" {
				genericUsed = false
				continue
			}
			out = append(out, s)
		}
	}
	return out, nil
}

