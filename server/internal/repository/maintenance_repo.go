func (r *MaintenanceRepo) InsertVisit(planID, visitDate, customerID string, sortOrder, autoGen int, entryCategory, notes string) error {
	return r.InsertVisitFull(model.MaintenanceVisit{
		PlanID: planID, VisitDate: visitDate, CustomerID: customerID,
		SortOrder: sortOrder, AutoGenerated: autoGen == 1,
		EntryCategory: entryCategory, Notes: notes,
	})
}

// InsertVisitFull 담당자·점검대상·완료여부까지 지정해 방문을 넣는다.
func (r *MaintenanceRepo) InsertVisitFull(v model.MaintenanceVisit) error {
	id := v.VisitID
	if id == "" {
		id = randomID("mvs_")
	}
	auto := 0
	if v.AutoGenerated {
		auto = 1
	}
	completed := 0
	completedDate := ""
	if v.Completed {
		completed = 1
		completedDate = v.DoneOn()
	}
	if v.EntryCategory == "" {
		v.EntryCategory = "normal"
	}
	_, err := r.db.Exec(`
		INSERT INTO maintenance_visits
		(visit_id, plan_id, visit_date, customer_id, sort_order, auto_generated, entry_category, notes,
		 assignee, product_type, completed, completed_date)
		VALUES (?,?,?,?,?,?,?,?,?,?,?,?)`,
		id, v.PlanID, v.VisitDate, v.CustomerID, v.SortOrder, auto, v.EntryCategory, nullIfEmpty(v.Notes),
		nullIfEmpty(v.Assignee), nullIfEmpty(v.ProductType), completed, nullIfEmpty(completedDate))
	return err
}

// UpdateVisit 방문 일정·담당자·점검대상 등을 수정한다.
func (r *MaintenanceRepo) UpdateVisit(v model.MaintenanceVisit) error {
	if v.VisitID == "" {
		return fmt.Errorf("방문 ID가 없습니다")
	}
	if v.VisitDate == "" || v.CustomerID == "" {
		return fmt.Errorf("날짜와 고객을 선택하세요")
	}
	if v.EntryCategory == "" {
		v.EntryCategory = "normal"
	}
	completed := 0
	completedDate := ""
	if v.Completed {
		completed = 1
		completedDate = v.DoneOn()
	}
	res, err := r.db.Exec(`
		UPDATE maintenance_visits SET
			visit_date=?, customer_id=?, entry_category=?, notes=?,
			assignee=?, product_type=?, completed=?, completed_date=?
		WHERE visit_id=?`,
		v.VisitDate, v.CustomerID, v.EntryCategory, nullIfEmpty(v.Notes),
		nullIfEmpty(v.Assignee), nullIfEmpty(v.ProductType),
		completed, nullIfEmpty(completedDate), v.VisitID)
	if err != nil {
		return err
	}
	n, _ := res.RowsAffected()
	if n == 0 {
		return fmt.Errorf("방문을 찾을 수 없습니다")
	}
	return nil
}

// SetVisitCompleted 방문 완료 표시를 켜고 끈다. 끄면 실제 방문일도 지운다.
func (r *MaintenanceRepo) SetVisitCompleted(visitID string, done bool, doneDate string) error {
	if !done {
		_, err := r.db.Exec(
			`UPDATE maintenance_visits SET completed=0, completed_date=NULL WHERE visit_id=?`, visitID)
		return err
	}
	if doneDate == "" {
		_, err := r.db.Exec(
			`UPDATE maintenance_visits SET completed=1, completed_date=visit_date WHERE visit_id=?`, visitID)
		return err
	}
	_, err := r.db.Exec(
		`UPDATE maintenance_visits SET completed=1, completed_date=? WHERE visit_id=?`, doneDate, visitID)
	return err
}

// CompleteVisitsUntil 지정일까지의 방문을 한 번에 완료 처리한다(과거 일정 일괄 정리용).
// onlyAssignees가 있으면 해당 담당자명만 처리한다(기술담당 내 일정 범위).
func (r *MaintenanceRepo) CompleteVisitsUntil(planID, until string, onlyAssignees []string) (int, error) {
	q := `
		UPDATE maintenance_visits
		SET completed=1, completed_date=COALESCE(NULLIF(completed_date,''), visit_date)
		WHERE plan_id=? AND visit_date <= ? AND COALESCE(completed,0)=0`
	args := []interface{}{planID, until}
	names := cleanAssignees(onlyAssignees)
	if len(names) > 0 {
		parts := make([]string, len(names))
		for i, n := range names {
			parts[i] = "LOWER(TRIM(COALESCE(assignee,''))) = LOWER(?)"
			args = append(args, n)
		}
		q += " AND (" + strings.Join(parts, " OR ") + ")"
	}
	res, err := r.db.Exec(q, args...)
	if err != nil {
		return 0, err
	}
	n, _ := res.RowsAffected()
	return int(n), nil
}

