	if err != nil {
		return nil, err
	}
	if existing != nil {
		return nil, fmt.Errorf("%d년 계획이 이미 있습니다", year)
	}
	id := randomID("mpl_")
	_, err = r.db.Exec(`
		INSERT INTO maintenance_plans (plan_id, plan_year, title, status, updated_at)
		VALUES (?, ?, ?, 'draft', CURRENT_TIMESTAMP)`, id, year, title)
