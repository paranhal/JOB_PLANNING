// HasVisitInMonth 해당 달·기관(·점검대상)에 방문이 있는지.
// product 가 있으면 슬롯 키(klas/rfid/generic)로 대상별로 판정한다.
func (r *MaintenanceRepo) HasVisitInMonth(planID, customerID string, year, month int, product string) bool {
	prefix := model.MonthPrefix(year, month) + "%"
	rows, err := r.db.Query(`
		SELECT COALESCE(product_type,'') FROM maintenance_visits
		WHERE plan_id=? AND customer_id=? AND visit_date LIKE ?`,
		planID, customerID, prefix)
	if err != nil {
		return false
	}
	defer rows.Close()
	want := strings.TrimSpace(product)
	wantKey := ""
	if want != "" {
		wantKey = model.VisitProductSlotKey(want)
	}
	any := false
	for rows.Next() {
		var pt string
		if err := rows.Scan(&pt); err != nil {
			return false
		}
		any = true
		if wantKey == "" {
			continue
		}
		if model.VisitProductSlotKey(pt) == wantKey {
			return true
		}
	}
	if wantKey != "" {
		return false
	}
	return any
}

// SetVisitDate 일일 업무 등록에서 점검 카드를 다른 날짜로 옮겼을 때 방문일을 맞춘다.
// 완료된 방문은 실적이므로 그대로 두고, 같은 날 같은 대상이 이미 있으면 조용히 넘긴다.
func (r *MaintenanceRepo) SetVisitDate(visitID, visitDate string) error {
	visitID = strings.TrimSpace(visitID)
	parsed, err := model.ParseAppDate(visitDate)
	if err != nil {
		return err
	}
	visitDate = parsed
	if visitID == "" || visitDate == "" {
		return nil
	}
	_, err = r.db.Exec(`
		UPDATE maintenance_visits SET visit_date=?
		WHERE visit_id=? AND visit_date!=? AND COALESCE(completed,0)=0`,
		visitDate, visitID, visitDate)
	if err != nil && strings.Contains(strings.ToUpper(err.Error()), "UNIQUE") {
		return nil
	}
	return err
}

// SetVisitCompleted 방문 완료 표시를 켜고 끈다. 끄면 실제 방문일도 지운다.
func (r *MaintenanceRepo) SetVisitCompleted(visitID string, done bool, doneDate string) error {
	var label string
	_ = r.db.QueryRow(`SELECT COALESCE(visit_date,'') FROM maintenance_visits WHERE visit_id=?`, visitID).Scan(&label)
	if label == "" {
		label = visitID
	}
	return touchUpdate(r.db, "maintenance_visits", "visit_id", visitID, label, func() error {
		if !done {
			_, err := r.db.Exec(
				`UPDATE maintenance_visits SET completed=0, completed_date=NULL WHERE visit_id=?`, visitID)
			return err
		}
		if doneDate == "" {
			_, err := r.db.Exec(
				`UPDATE maintenance_visits SET completed=1, completed_date=visit_date WHERE visit_id=?`, visitID)
			return err
		}
		_, err := r.db.Exec(
			`UPDATE maintenance_visits SET completed=1, completed_date=? WHERE visit_id=?`, doneDate, visitID)
		return err
	})
}

// CompleteVisitsUntil 지정일까지의 방문을 한 번에 완료 처리한다(과거 일정 일괄 정리용).
// onlyAssignees가 있으면 해당 담당자명만 처리한다(기술담당 내 일정 범위).
func (r *MaintenanceRepo) CompleteVisitsUntil(planID, until string, onlyAssignees []string) (int, error) {
	where := `plan_id=? AND visit_date <= ? AND COALESCE(completed,0)=0`
	args := []interface{}{planID, until}
	names := cleanAssignees(onlyAssignees)
	if len(names) > 0 {
		parts := make([]string, len(names))
		for i, n := range names {
			parts[i] = "LOWER(TRIM(COALESCE(assignee,''))) = LOWER(?)"
			args = append(args, n)
		}
		where += " AND (" + strings.Join(parts, " OR ") + ")"
	}
	rows, err := r.db.Query(`SELECT visit_id, COALESCE(visit_date,'') FROM maintenance_visits WHERE `+where, args...)
	if err != nil {
		return 0, err
	}
	type hit struct{ id, date, before string }
	var hits []hit
	for rows.Next() {
		var id, date string
		if err := rows.Scan(&id, &date); err != nil {
			rows.Close()
			return 0, err
		}
		hits = append(hits, hit{id: id, date: date})
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return 0, err
	}
	if len(hits) == 0 {
		return 0, nil
	}
	for i := range hits {
		hits[i].before = rowJSON(r.db, "maintenance_visits", "visit_id", hits[i].id)
	}
	res, err := r.db.Exec(`
		UPDATE maintenance_visits
		SET completed=1, completed_date=COALESCE(NULLIF(completed_date,''), visit_date)
		WHERE `+where, args...)
	if err != nil {
		return 0, err
	}
	for _, h := range hits {
		logUpdate(r.db, "maintenance_visits", "visit_id", h.id, h.date, h.before)
	}
	n, _ := res.RowsAffected()
	return int(n), nil
}

