func (r *MaintenanceRepo) DeletePlan(planID string) error {
	tx, err := r.db.Begin()
	if err != nil {
		return err
	}
	if _, err := tx.Exec(`DELETE FROM maintenance_visits WHERE plan_id = ?`, planID); err != nil {
		_ = tx.Rollback()
		return err
	}
	if _, err := tx.Exec(`DELETE FROM maintenance_plans WHERE plan_id = ?`, planID); err != nil {
		_ = tx.Rollback()
		return err
	}
	return tx.Commit()
}

// visitSelectColumns 방문 목록 공통 컬럼 (scanVisits와 순서를 맞춘다)
const visitSelectColumns = `
		SELECT v.visit_id, v.plan_id, v.visit_date, v.customer_id,
		       COALESCE(c.org_name,''), COALESCE(cfg.short_name, c.org_name),
		       v.sort_order, v.auto_generated, v.entry_category, COALESCE(v.notes,''),
		       COALESCE(v.assignee,''), COALESCE(v.product_type,''),
		       COALESCE(v.completed,0), COALESCE(v.completed_date,'')
		FROM maintenance_visits v
		JOIN customers c ON c.customer_id = v.customer_id
		LEFT JOIN maintenance_site_config cfg ON cfg.customer_id = v.customer_id`

func (r *MaintenanceRepo) ListVisits(planID string) ([]model.MaintenanceVisit, error) {
	rows, err := r.db.Query(visitSelectColumns+`
		WHERE v.plan_id = ?
		ORDER BY v.visit_date, v.sort_order, cfg.short_name`, planID)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	return scanVisits(rows)
}

func scanVisits(rows *sql.Rows) ([]model.MaintenanceVisit, error) {
	var out []model.MaintenanceVisit
	for rows.Next() {
		var v model.MaintenanceVisit
		var auto, completed int
		if err := rows.Scan(&v.VisitID, &v.PlanID, &v.VisitDate, &v.CustomerID,
			&v.OrgName, &v.ShortName, &v.SortOrder, &auto, &v.EntryCategory, &v.Notes,
			&v.Assignee, &v.ProductType, &completed, &v.CompletedDate); err != nil {
			return nil, err
		}
		v.AutoGenerated = auto == 1
		v.Completed = completed == 1
		out = append(out, v)
	}
	return out, rows.Err()
}

func (r *MaintenanceRepo) ListVisitsByMonth(planID string, year, month int) ([]model.MaintenanceVisit, error) {
	prefix := fmt.Sprintf("%d-%02d-%%", year, month)
	rows, err := r.db.Query(visitSelectColumns+`
		WHERE v.plan_id = ? AND v.visit_date LIKE ?
		ORDER BY v.visit_date, v.sort_order`, planID, prefix)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	return scanVisits(rows)
}

// ListVisitsBetween 기간 안의 모든 계획 방문 (업무 등록 화면의 정기점검 카드용)
func (r *MaintenanceRepo) ListVisitsBetween(from, to string) ([]model.MaintenanceVisit, error) {
	rows, err := r.db.Query(visitSelectColumns+`
		WHERE v.visit_date >= ? AND v.visit_date <= ?
		ORDER BY v.visit_date, v.sort_order`, from, to)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	return scanVisits(rows)
}

