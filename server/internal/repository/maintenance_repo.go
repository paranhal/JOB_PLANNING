func (r *MaintenanceRepo) deleteAutoVisitsFiltered(planID, monthPrefix string, useTodayProtect bool) (deleted, skipped int, err error) {
	q := `SELECT visit_id, visit_date, COALESCE(completed,0) FROM maintenance_visits WHERE plan_id = ? AND auto_generated = 1`
	args := []interface{}{planID}
	if monthPrefix != "" {
		q += ` AND visit_date LIKE ?`
		args = append(args, monthPrefix+"%")
	}
	rows, err := r.db.Query(q, args...)
	if err != nil {
		return 0, 0, err
	}
	type row struct {
		id, date string
		done     int
	}
	var list []row
	for rows.Next() {
		var x row
		if err := rows.Scan(&x.id, &x.date, &x.done); err != nil {
			rows.Close()
			return 0, 0, err
		}
		list = append(list, x)
	}
	rows.Close()
	now := r.nowTime()
	for _, x := range list {
		protect := model.VisitDeleteProtected(x.date, now)
		if useTodayProtect {
			protect = model.VisitAutoReassignProtected(x.date, now)
		}
		if x.done == 1 || protect {
			skipped++
			continue
		}
		var err error
		if useTodayProtect {
			err = r.removeVisitRow(x.id)
		} else {
			err = r.DeleteVisit(x.id)
		}
		if err != nil {
			if errors.Is(err, ErrVisitDeleteProtected) {
				skipped++
				continue
			}
			return deleted, skipped, err
		}
		deleted++
	}
	return deleted, skipped, nil
}

func (r *MaintenanceRepo) deleteVisitsLogged(where string, args ...interface{}) error {
	rows, err := r.db.Query(`SELECT visit_id FROM maintenance_visits WHERE `+where, args...)
	if err != nil {
		return err
	}
	var ids []string
	for rows.Next() {
		var id string
		if err := rows.Scan(&id); err != nil {
			rows.Close()
			return err
		}
		ids = append(ids, id)
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return err
	}
	for _, id := range ids {
		if err := r.DeleteVisit(id); err != nil {
			return err
		}
	}
	return nil
}

