// periodicCycleRank 점검 간격이 짧은 순. 한 기관에 주기가 섞여 있으면 가장 짧은 주기를 따른다.
var periodicCycleRank = map[string]int{
	"monthly":        1,
	"odd_bimonthly":  2,
	"even_bimonthly": 2,
	"quarterly":      3,
	"semi":           4,
	"yearly":         5,
}

// SiteConfigSyncResult 자산 기준 일괄 생성 결과
type SiteConfigSyncResult struct {
	Added   int      // 새로 만든 사이트 설정 수
	Skipped int      // 이미 설정이 있어 건너뛴 기관 수
	Names   []string // 새로 만든 기관명
}

// SyncSiteConfigsFromAssets 유상 유지보수 계약 + 정기 점검주기를 가진 자산의 기관에
// 점검 사이트 설정을 만든다. 이미 설정이 있는 기관은 손대지 않는다.
func (r *MaintenanceRepo) SyncSiteConfigsFromAssets() (SiteConfigSyncResult, error) {
	var res SiteConfigSyncResult
	targets, skipped, err := r.siteConfigCandidates()
	if err != nil {
		return res, err
	}
	res.Skipped = skipped

	for _, cfg := range targets {
		c := cfg
		if err := r.UpsertSiteConfig(&c); err != nil {
			return res, fmt.Errorf("%s 설정 생성: %w", c.ShortName, err)
		}
		res.Added++
		res.Names = append(res.Names, c.ShortName)
	}
	return res, nil
}

// PreviewSiteConfigsFromAssets 저장하지 않고 추가 대상만 계산
func (r *MaintenanceRepo) PreviewSiteConfigsFromAssets() ([]model.MaintenanceSiteConfig, error) {
	targets, _, err := r.siteConfigCandidates()
	return targets, err
}

func (r *MaintenanceRepo) siteConfigCandidates() ([]model.MaintenanceSiteConfig, int, error) {
	skipped := 0
	rows, err := r.db.Query(`
		SELECT a.customer_id,
		       COALESCE(NULLIF(TRIM(c.org_name),''), NULLIF(TRIM(c.official_name),''), a.customer_id),
		       COALESCE(c.addr_sido,''),
		       GROUP_CONCAT(DISTINCT TRIM(LOWER(a.maint_cycle))),
		       MAX(CASE WHEN LOWER(COALESCE(a.product_category,'')) = 'rfid' THEN 1 ELSE 0 END),
		       MAX(CASE WHEN UPPER(COALESCE(a.product_name,'')) LIKE '%KLAS%'
		                  OR UPPER(COALESCE(a.model_name,'')) LIKE '%KLAS%' THEN 1 ELSE 0 END),
		       MAX(CASE WHEN EXISTS (SELECT 1 FROM maintenance_site_config s
		                             WHERE s.customer_id = a.customer_id) THEN 1 ELSE 0 END)
		FROM assets a
		JOIN customers c ON c.customer_id = a.customer_id
		WHERE TRIM(LOWER(COALESCE(a.maint_contract_type,''))) = 'paid'
		  AND TRIM(LOWER(COALESCE(a.maint_cycle,''))) IN
		      ('monthly','odd_bimonthly','even_bimonthly','quarterly','semi','yearly')
		GROUP BY a.customer_id
		ORDER BY 2`)
	if err != nil {
		return nil, 0, err
	}
	defer rows.Close()

	var targets []model.MaintenanceSiteConfig
	for rows.Next() {
		var customerID, orgName, sido, cycles string
		var hasRfid, hasKlas, exists int
		if err := rows.Scan(&customerID, &orgName, &sido, &cycles, &hasRfid, &hasKlas, &exists); err != nil {
			return nil, 0, err
		}
		if exists == 1 {
			skipped++
			continue
		}
		targets = append(targets, model.MaintenanceSiteConfig{
			CustomerID:      customerID,
			ShortName:       strings.TrimSpace(orgName),
			Region:          shortRegionName(sido),
			HasKlas:         hasKlas == 1,
			HasRfid:         hasRfid == 1,
			InspectionCycle: shortestCycle(cycles),
			EntryCategory:   "normal",
			OrgName:         strings.TrimSpace(orgName),
		})
	}
	if err := rows.Err(); err != nil {
		return nil, 0, err
	}
	return targets, skipped, nil
}

// shortestCycle GROUP_CONCAT 으로 모인 주기 중 간격이 가장 짧은 값
func shortestCycle(concat string) string {
	best, bestRank := "monthly", 99
	for _, v := range strings.Split(concat, ",") {
		v = strings.TrimSpace(v)
		rank, ok := periodicCycleRank[v]
		if ok && rank < bestRank {
			best, bestRank = v, rank
		}
	}
	return best
}

// shortRegionName 행정구역 정식명칭을 점검표에 쓰는 축약형으로 (충청남도 → 충남)
func shortRegionName(sido string) string {
	s := strings.TrimSpace(sido)
	if s == "" {
		return ""
	}
	short := map[string]string{
		"서울특별시": "서울", "부산광역시": "부산", "대구광역시": "대구", "인천광역시": "인천",
		"광주광역시": "광주", "대전광역시": "대전", "울산광역시": "울산",
		"세종특별자치시": "세종", "경기도": "경기", "강원도": "강원", "강원특별자치도": "강원",
		"충청북도": "충북", "충청남도": "충남", "전라북도": "전북", "전북특별자치도": "전북",
		"전라남도": "전남", "경상북도": "경북", "경상남도": "경남",
		"제주도": "제주", "제주특별자치도": "제주",
	}
	if v, ok := short[s]; ok {
		return v
	}
	return s
}

