func protectRepo(t *testing.T, name string) (*MaintenanceRepo, func()) {
	t.Helper()
	db, err := InitDB(filepath.Join(t.TempDir(), name))
	if err != nil {
		t.Fatal(err)
	}
	if _, err := db.Exec(`INSERT INTO customers (customer_id, org_name, official_name, is_active)
		VALUES ('c1','가나도서관','가나도서관',1)`); err != nil {
		t.Fatal(err)
	}
	repo := NewMaintenanceRepo(db)
	repo.Now = func() time.Time { return time.Date(2026, 8, 17, 12, 0, 0, 0, time.Local) }
	return repo, func() { db.Close() }
}

func TestDeleteVisitRejectsCurrentAndPastMonth(t *testing.T) {
	repo, close := protectRepo(t, "del_protect.db")
	defer close()
	p, err := repo.CreatePlan(2026, "2026년 정기점검")
	if err != nil {
		t.Fatal(err)
	}
	for _, date := range []string{"2026-07-10", "2026-08-10"} {
		if err := repo.InsertVisit(p.PlanID, date, "c1", 0, 0, "normal", ""); err != nil {
			t.Fatal(err)
		}
	}
	visits, _ := repo.ListVisits(p.PlanID)
	if len(visits) != 2 {
		t.Fatalf("setup: %d", len(visits))
	}
	for _, v := range visits {
		if err := repo.DeleteVisit(v.VisitID); !errors.Is(err, ErrVisitDeleteProtected) {
			t.Fatalf("%s 삭제 오류: %v", v.VisitDate, err)
		}
	}
	left, _ := repo.ListVisits(p.PlanID)
	if len(left) != 2 {
		t.Fatalf("보호 방문이 지워짐: %d", len(left))
	}
}

