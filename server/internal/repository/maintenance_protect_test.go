func TestCollapseDuplicateSkipsProtected(t *testing.T) {
	repo, close := protectRepo(t, "collapse_protect.db")
	defer close()
	p, err := repo.CreatePlan(2026, "t")
	if err != nil {
		t.Fatal(err)
	}
	if err := repo.InsertVisitFull(model.MaintenanceVisit{
		PlanID: p.PlanID, VisitDate: "2026-08-10", CustomerID: "c1", ProductType: "KLAS", AutoGenerated: true,
	}); err != nil {
		t.Fatal(err)
	}
	if err := repo.InsertVisitFull(model.MaintenanceVisit{
		PlanID: p.PlanID, VisitDate: "2026-08-14", CustomerID: "c1", ProductType: "KLAS",
	}); err != nil {
		t.Fatal(err)
	}
	deleted, skipped, err := repo.CollapseDuplicateMonthVisits(p.PlanID, 2026, 8)
	if err != nil {
		t.Fatal(err)
	}
	if deleted != 0 || skipped != 1 {
		t.Fatalf("deleted=%d skipped=%d (당월 중복은 지우면 안 됨)", deleted, skipped)
	}
	left, _ := repo.ListVisitsByMonth(p.PlanID, 2026, 8)
	if len(left) != 2 {
		t.Fatalf("당월 중복이 지워짐: %d", len(left))
	}
}
