func TestDeleteVisitIDsSkipsProtected(t *testing.T) {
	repo, close := protectRepo(t, "bulk.db")
	defer close()
	p, err := repo.CreatePlan(2026, "t")
	if err != nil {
		t.Fatal(err)
	}
	if err := repo.InsertVisit(p.PlanID, "2026-08-10", "c1", 0, 0, "normal", "당월"); err != nil {
		t.Fatal(err)
	}
	if err := repo.InsertVisit(p.PlanID, "2026-09-10", "c1", 0, 0, "normal", "다음달"); err != nil {
		t.Fatal(err)
	}
	visits, _ := repo.ListVisits(p.PlanID)
	ids := []string{visits[0].VisitID, visits[1].VisitID}
	deleted, skipped, err := repo.DeleteVisitIDs(ids)
	if err != nil {
		t.Fatal(err)
	}
	if deleted != 1 || skipped != 1 {
		t.Fatalf("deleted=%d skipped=%d", deleted, skipped)
	}
	left, _ := repo.ListVisits(p.PlanID)
	if len(left) != 1 || left[0].VisitDate != "2026-08-10" {
		t.Fatalf("남은 방문: %+v", left)
	}
}

func TestDeletePlanRejectsProtectedAndCompleted(t *testing.T) {
	repo, close := protectRepo(t, "plan_guard.db")
	defer close()
	p, err := repo.CreatePlan(2026, "2026년 정기점검")
	if err != nil {
		t.Fatal(err)
	}
	if err := repo.InsertVisit(p.PlanID, "2026-08-10", "c1", 0, 0, "normal", ""); err != nil {
		t.Fatal(err)
	}
	err = repo.DeletePlan(p.PlanID)
	if err == nil || err.Error() == "" {
		t.Fatal("당월 방문이 있는데 계획이 지워짐")
	}
	if got := err.Error(); got != model.ProtectedVisitRangeMessage(repo.Now(), 1) {
		t.Fatalf("거부 문구: %s", got)
	}
	if _, err := repo.GetPlan(p.PlanID); err != nil {
		t.Fatal(err)
	}

	fut, err := repo.CreatePlan(2027, "2027년 정기점검")
	if err != nil {
		t.Fatal(err)
	}
	if err := repo.InsertVisit(fut.PlanID, "2027-03-10", "c1", 0, 0, "normal", ""); err != nil {
		t.Fatal(err)
	}
	visits, _ := repo.ListVisits(fut.PlanID)
	if err := repo.SetVisitCompleted(visits[0].VisitID, true, "2027-03-10"); err != nil {
		t.Fatal(err)
	}
	if err := repo.DeletePlan(fut.PlanID); err == nil {
		t.Fatal("완료 방문이 있는데 계획이 지워짐")
	}
}

