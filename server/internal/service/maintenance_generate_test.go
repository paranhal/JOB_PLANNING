func TestAutoGenerateOverflowStaysUnassigned(t *testing.T) {
	dir := t.TempDir()
	db, err := repository.InitDB(filepath.Join(dir, "cap.db"))
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	if _, err := db.Exec(`INSERT INTO app_settings(setting_key, setting_value, updated_at)
		VALUES (?, '1', '2026-01-01T00:00:00Z')`, repository.SettingMaintenanceAutoDailyLimit); err != nil {
		t.Fatal(err)
	}
	repo := repository.NewMaintenanceRepo(db)
	const nSites = 20
	for i := 0; i < nSites; i++ {
		id := fmt.Sprintf("c%02d", i)
		if _, err := db.Exec(`INSERT INTO customers (customer_id, org_name, official_name, is_active)
			VALUES (?,?,?,1)`, id, id, id); err != nil {
			t.Fatal(err)
		}
		if err := repo.UpsertSiteConfig(&model.MaintenanceSiteConfig{
			CustomerID: id, ShortName: id, Region: "R",
			HasKlas: true, InspectionCycle: "yearly",
		}); err != nil {
			t.Fatal(err)
		}
	}
	p, err := repo.CreatePlan(2026, "상한")
	if err != nil {
		t.Fatal(err)
	}
	if err := AutoGenerateMaintenance(repo, p.PlanID); err != nil {
		t.Fatal(err)
	}

	jan, err := repo.ListVisitsByMonth(p.PlanID, 2026, 1)
	if err != nil {
		t.Fatal(err)
	}
	workdays := workdaysBefore25(2026, 1, time.Local, NewCalendar(repo.Holidays()))
	if len(jan) != len(workdays) {
		t.Fatalf("1월 방문=%d want %d (하루 1건 × 25일 이전 평일)", len(jan), len(workdays))
	}
	for _, v := range jan {
		day, _ := strconv.Atoi(v.VisitDate[8:10])
		if day > 24 {
			t.Fatalf("26일 이후로 밀어 넣음: %s", v.VisitDate)
		}
	}
	unassigned, err := repo.ListUnassignedMonthSlots(p.PlanID, 2026, 1)
	if err != nil {
		t.Fatal(err)
	}
	wantLeft := nSites - len(workdays)
	if len(unassigned) != wantLeft {
		t.Fatalf("미배정=%d want %d", len(unassigned), wantLeft)
	}
	aug, _ := repo.ListVisitsByMonth(p.PlanID, 2026, 8)
	if len(aug) != 0 {
		t.Fatalf("년1회인데 8월 방문=%d", len(aug))
	}
}

