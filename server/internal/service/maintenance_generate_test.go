	if err := mnt.UpsertSiteConfig(&model.MaintenanceSiteConfig{
		CustomerID: "c1", ShortName: "도서관", Region: "R1", HasKlas: true, InspectionCycle: "monthly",
	}); err != nil {
		t.Fatal(err)
	}
	prev, err := mnt.CreatePlan(2025, "2025")
	if err != nil {
		t.Fatal(err)
	}
	if err := mnt.InsertVisitFull(model.MaintenanceVisit{
		PlanID: prev.PlanID, VisitDate: "2025-12-10", CustomerID: "c1", ProductType: "KLAS", Assignee: "양기헌",
	}); err != nil {
		t.Fatal(err)
	}
